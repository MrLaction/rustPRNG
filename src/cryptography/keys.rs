use rsa::{
    BigUint as RsaBigUint,
    RsaPrivateKey,
    RsaPublicKey,
    traits::PublicKeyParts,
};

use super::primes::{PrimePair, PUBLIC_EXPONENT};

pub fn build_key_pair(
    pair: &PrimePair,
) -> Result<(RsaPrivateKey, RsaPublicKey), String> {
    if pair.p.bits() != 1024 || pair.q.bits() != 1024 {
        return Err("Both factors must have exactly 1024 bits.".to_string());
    }

    if pair.p == pair.q {
        return Err("The RSA factors must be different.".to_string());
    }

    //The RSA crate uses a different BigUint type. Byte conversion preserves the exact values generated by our program.
    let p = RsaBigUint::from_bytes_be(&pair.p.to_bytes_be());
    let q = RsaBigUint::from_bytes_be(&pair.q.to_bytes_be());
    let exponent = RsaBigUint::from(PUBLIC_EXPONENT);

    //Construct the key from our factors without generating replacement primes. This computes n = p * q and d = e^(-1) mod lcm(p - 1, q - 1).
    let private_key = RsaPrivateKey::from_p_q(p, q, exponent)
        .map_err(|error| format!("Could not construct the RSA key: {error}"))?;

    if private_key.n().bits() != 2048 {
        return Err("The RSA modulus must have exactly 2048 bits.".to_string());
    }

    let public_key = RsaPublicKey::from(&private_key);

    Ok((private_key, public_key))
}

#[cfg(test)]
mod tests {
    use super::*;

    use rand::rngs::OsRng;
    use rsa::{Oaep, traits::PrivateKeyParts};
    use sha2::Sha256;

    use crate::cryptography::primes::generate_prime_pair;

    #[test]
    fn preserves_generated_factors_and_supports_oaep() {
        let pair = generate_prime_pair()
            .expect("Prime generation failed");

        let expected_p = RsaBigUint::from_bytes_be(&pair.p.to_bytes_be());
        let expected_q = RsaBigUint::from_bytes_be(&pair.q.to_bytes_be());
        let expected_modulus = &expected_p * &expected_q;

        let (private_key, public_key) = build_key_pair(&pair)
            .expect("Key construction failed");

        //Verify that the library kept our original factors.
        assert_eq!(
            private_key.primes(),
            &[expected_p.clone(), expected_q.clone()]
        );
        assert_eq!(public_key.n(), &expected_modulus);

        //Check the inverse relation for both factors.
        let one = RsaBigUint::from(1u32);
        let ed = public_key.e() * private_key.d();

        assert_eq!(&ed % (&expected_p - &one), one);
        assert_eq!(&ed % (&expected_q - &one), one);

        let mut rng = OsRng;

        //Exercise empty input, Unicode, and the maximum OAEP message length.
        let messages = [
            Vec::new(),
            "Hello, receiver! ñ 🔐".as_bytes().to_vec(),
            vec![0u8; 190],
        ];

        for message in messages {
            let ciphertext = public_key
                .encrypt(&mut rng, Oaep::new::<Sha256>(), &message)
                .expect("Encryption failed");

            assert_eq!(ciphertext.len(), 256);

            let recovered = private_key
                .decrypt_blinded(
                    &mut rng,
                    Oaep::new::<Sha256>(),
                    &ciphertext,
                )
                .expect("Decryption failed");

            assert_eq!(recovered, message);
        }

        //A 2048-bit modulus with SHA-256 supports at most 190 OAEP bytes.
        assert!(
            public_key
                .encrypt(
                    &mut rng,
                    Oaep::new::<Sha256>(),
                    &[0u8; 191],
                )
                .is_err()
        );

        //An all-zero ciphertext is not a valid OAEP encoding.
        assert!(
            private_key
                .decrypt_blinded(
                    &mut rng,
                    Oaep::new::<Sha256>(),
                    &[0u8; 256],
                )
                .is_err()
        );
    }
}